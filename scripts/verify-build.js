/**
 * Spelling Bee Hive — Build, Bundle & Static Integrity Verification Script
 *
 * 1. Bundles the modular ES sources (`words.js`, `gameState.js`, `audioManager.js`, `app.js`)
 *    into `src/bundle.js` so `index.html` works both directly from disk (`file://`)
 *    AND over HTTP (`http://localhost:3000`) without CORS module errors.
 * 2. Verifies all required files, assets, word bank rules, and game initializers.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { WORD_BANK, validateWordBank, DIFFICULTY_CONFIG } from '../src/data/words.js';
import { createInitialState, startSession } from '../src/engine/gameState.js';
import { AudioManager } from '../src/audio/audioManager.js';
import { renderBeeSvg, renderHiveSvg, renderGardenBackdropSvg } from '../src/ui/app.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

function stripModuleSyntax(code) {
  return code
    // Remove multi-line or single-line import statements
    .replace(/^\s*import\s+[\s\S]*?from\s+['"][^'"]+['"];?\s*$/gm, '')
    // Replace `export const/let/var/function/class` with `const/let/var/function/class`
    .replace(/^\s*export\s+(const|let|var|function|class)\s+/gm, '$1 ');
}

const moduleOrder = [
  'src/data/words.js',
  'src/engine/gameState.js',
  'src/audio/audioManager.js',
  'src/ui/app.js'
];

const bundledParts = moduleOrder.map((rel) => {
  const raw = fs.readFileSync(path.join(rootDir, rel), 'utf8');
  return `// --- ${rel} ---\n${stripModuleSyntax(raw)}`;
});

const bundleContent = `/**
 * Spelling Bee Hive — Standalone Browser Bundle (Auto-generated by scripts/verify-build.js)
 * Works directly via file:// (double-clicking index.html) and via HTTP server.
 */
(function () {
  'use strict';
${bundledParts.join('\n\n')}
})();
`;

fs.writeFileSync(path.join(rootDir, 'src', 'bundle.js'), bundleContent, 'utf8');

const requiredFiles = [
  'package.json',
  'index.html',
  'src/styles/main.css',
  'src/data/words.js',
  'src/engine/gameState.js',
  'src/audio/audioManager.js',
  'src/ui/app.js',
  'src/bundle.js',
  'src/assets/welcome-scene.png',
  'src/assets/gameplay-garden-bg.jpg',
  'src/assets/bee-sprite.png',
  'tests/game.test.js'
];

let failed = false;

function assertCheck(condition, message) {
  if (!condition) {
    console.error(`❌ CHECK FAILED: ${message}`);
    failed = true;
  } else {
    console.log(`✅ ${message}`);
  }
}

console.log('=== Spelling Bee Hive: Build & Integrity Check ===');

for (const relPath of requiredFiles) {
  const fullPath = path.join(rootDir, relPath);
  const exists = fs.existsSync(fullPath);
  const size = exists ? fs.statSync(fullPath).size : 0;
  assertCheck(exists && size > 0, `File present and non-empty: ${relPath} (${size} bytes)`);
}

// Validate Word Bank
const validation = validateWordBank(WORD_BANK);
assertCheck(
  validation.valid,
  `Word bank validation (${WORD_BANK.length} words): ${
    validation.valid ? 'ALL VALID' : validation.errors.join('; ')
  }`
);

// Verify difficulties exist
for (const diffKey of ['easy', 'medium', 'hard']) {
  const state = startSession(createInitialState(), diffKey);
  assertCheck(
    state.sessionWords.length >= DIFFICULTY_CONFIG[diffKey].sessionLength,
    `Difficulty "${diffKey}" (${DIFFICULTY_CONFIG[diffKey].title}) initializes with ${state.sessionWords.length} words`
  );
}

// Verify AudioManager instantiates cleanly in headless Node
const audio = new AudioManager({ muted: false });
assertCheck(typeof audio.speakWord === 'function', 'AudioManager exports required playback methods');

// Verify SVG asset renderers produce valid SVG markup
assertCheck(renderBeeSvg().includes('<svg'), 'Bee SVG renderer outputs valid SVG markup');
assertCheck(renderHiveSvg().includes('<svg'), 'Hive SVG renderer outputs valid SVG markup');
assertCheck(renderGardenBackdropSvg().includes('<svg'), 'Garden backdrop renderer outputs valid SVG markup');

if (failed) {
  process.exit(1);
} else {
  console.log('=== All build and lint checks passed! ===');
}
